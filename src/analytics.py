"""Analytics, drilldown aggregations, ground-truth evaluation, and business Q&A engine.

Implements Sections 19 through 25, 31, 32, 33, and 34 of the project specification.
"""

from typing import Dict, Any, Tuple
import pandas as pd
import numpy as np


def get_suspicious_queue(df: pd.DataFrame) -> pd.DataFrame:
    """Filter and prioritize suspicious transactions for manual investigator review."""
    suspicious = df[df["Suspicious"] == 1].copy()
    sort_cols = ["Suspicion_Score", "Amount"]
    available_sort = [c for c in sort_cols if c in suspicious.columns]
    
    preferred_cols = [
        "Transaction_ID", "Account_ID", "Transaction_Date", "Transaction_Time",
        "Amount", "Transaction_Type", "Channel", "Hour", "Txn_Count_1H",
        "Rule_High_Amount", "Rule_Late_Night", "Rule_High_Frequency",
        "Suspicion_Score", "Suspicious", "Rule_Combination", "Fraud_Label"
    ]
    cols_to_show = [c for c in preferred_cols if c in suspicious.columns]
    return suspicious[cols_to_show].sort_values(by=available_sort, ascending=False).reset_index(drop=True)


def get_type_analysis(df: pd.DataFrame) -> pd.DataFrame:
    """Analyze suspicious transaction rates grouped by Transaction_Type."""
    type_col = "Transaction_Type" if "Transaction_Type" in df.columns else None
    if not type_col:
        return pd.DataFrame()

    analysis = (
        df.groupby(type_col)
          .agg(
              Transactions=("Transaction_ID", "count"),
              Suspicious=("Suspicious", "sum"),
              Suspicious_Rate=("Suspicious", "mean")
          )
          .reset_index()
    )
    analysis["Suspicious_Rate"] = round(analysis["Suspicious_Rate"] * 100.0, 2)
    return analysis.sort_values(by="Suspicious_Rate", ascending=False).reset_index(drop=True)


def get_channel_analysis(df: pd.DataFrame) -> pd.DataFrame:
    """Analyze suspicious transaction rates grouped by Channel."""
    ch_col = "Channel" if "Channel" in df.columns else None
    if not ch_col:
        return pd.DataFrame()

    analysis = (
        df.groupby(ch_col)
          .agg(
              Transactions=("Transaction_ID", "count"),
              Suspicious=("Suspicious", "sum"),
              Suspicious_Rate=("Suspicious", "mean")
          )
          .reset_index()
    )
    analysis["Suspicious_Rate"] = round(analysis["Suspicious_Rate"] * 100.0, 2)
    return analysis.sort_values(by="Suspicious_Rate", ascending=False).reset_index(drop=True)


def get_hour_analysis(df: pd.DataFrame) -> pd.DataFrame:
    """Analyze transaction volume and suspicious alerts grouped by Hour (0-23)."""
    if "Hour" not in df.columns:
        return pd.DataFrame()

    analysis = (
        df.groupby("Hour")
          .agg(
              Transactions=("Transaction_ID", "count"),
              Suspicious=("Suspicious", "sum")
          )
          .reset_index()
    )
    analysis["Suspicious_Rate"] = round(
        (analysis["Suspicious"] / analysis["Transactions"].replace(0, np.nan)) * 100.0, 2
    ).fillna(0.0)
    return analysis.sort_values(by="Hour").reset_index(drop=True)


def get_account_risk_analysis(df: pd.DataFrame) -> pd.DataFrame:
    """Analyze customer accounts with repeated suspicious activities."""
    if "Account_ID" not in df.columns:
        return pd.DataFrame()

    analysis = (
        df.groupby("Account_ID")
          .agg(
              Transactions=("Transaction_ID", "count"),
              Total_Value=("Amount", "sum"),
              Avg_Amount=("Amount", "mean"),
              Suspicious_Transactions=("Suspicious", "sum")
          )
          .reset_index()
    )
    analysis["Total_Value"] = analysis["Total_Value"].round(2)
    analysis["Avg_Amount"] = analysis["Avg_Amount"].round(2)
    analysis["Suspicious_Rate"] = round(
        (analysis["Suspicious_Transactions"] / analysis["Transactions"]) * 100.0, 2
    )
    return analysis.sort_values(by=["Suspicious_Transactions", "Total_Value"], ascending=False).reset_index(drop=True)


def get_pattern_summary(df: pd.DataFrame) -> pd.DataFrame:
    """Summarize the total alerts generated by each individual rule."""
    summary_data = {
        "Pattern": ["High Amount", "Late Night", "High Frequency"],
        "Rule_Name": ["Rule_High_Amount", "Rule_Late_Night", "Rule_High_Frequency"],
        "Alerts": [
            int(df["Rule_High_Amount"].sum()) if "Rule_High_Amount" in df.columns else 0,
            int(df["Rule_Late_Night"].sum()) if "Rule_Late_Night" in df.columns else 0,
            int(df["Rule_High_Frequency"].sum()) if "Rule_High_Frequency" in df.columns else 0,
        ]
    }
    res = pd.DataFrame(summary_data)
    res["Alert_Pct"] = round((res["Alerts"] / len(df)) * 100.0, 2)
    return res


def get_rule_combination_analysis(df: pd.DataFrame) -> pd.DataFrame:
    """Analyze frequency and interpretation of rule combination bitmasks."""
    if "Rule_Combination" not in df.columns:
        return pd.DataFrame()

    comb = (
        df["Rule_Combination"]
        .value_counts()
        .reset_index()
    )
    comb.columns = ["Rule_Combination", "Transactions"]
    comb["Percentage"] = round((comb["Transactions"] / len(df)) * 100.0, 2)

    # Human-friendly descriptions
    descriptions = {
        "0_0_0": "Baseline / Normal (No Rules Triggered)",
        "1_0_0": "High Amount Only",
        "0_1_0": "Late Night Only",
        "0_0_1": "High Frequency Only",
        "1_1_0": "High Amount + Late Night",
        "1_0_1": "High Amount + High Frequency",
        "0_1_1": "Late Night + High Frequency",
        "1_1_1": "Critical Alert (All 3 Rules Triggered)",
    }
    comb["Description"] = comb["Rule_Combination"].map(descriptions).fillna("Custom Pattern")
    return comb.sort_values(by="Transactions", ascending=False).reset_index(drop=True)


def evaluate_against_ground_truth(df: pd.DataFrame) -> Dict[str, Any]:
    """Compare rule-based alerts against verified historical Fraud_Label."""
    if "Fraud_Label" not in df.columns:
        return {"status": "Fraud_Label not present in dataset"}

    # Actual: Fraud_Label (1 = Fraud, 0 = Legitimate)
    # Predicted: Suspicious (1 = Flagged, 0 = Clean)
    y_true = df["Fraud_Label"]
    y_pred = df["Suspicious"]

    tp = int(((y_true == 1) & (y_pred == 1)).sum())
    fp = int(((y_true == 0) & (y_pred == 1)).sum())
    tn = int(((y_true == 0) & (y_pred == 0)).sum())
    fn = int(((y_true == 1) & (y_pred == 0)).sum())

    total = len(df)
    precision = float(tp / (tp + fp)) if (tp + fp) > 0 else 0.0
    recall = float(tp / (tp + fn)) if (tp + fn) > 0 else 0.0
    f1 = float(2 * (precision * recall) / (precision + recall)) if (precision + recall) > 0 else 0.0
    specificity = float(tn / (tn + fp)) if (tn + fp) > 0 else 0.0
    fpr = float(fp / (fp + tn)) if (fp + tn) > 0 else 0.0
    accuracy = float((tp + tn) / total) if total > 0 else 0.0

    crosstab_df = pd.crosstab(
        df["Fraud_Label"],
        df["Suspicious"],
        rownames=["Actual Fraud (Fraud_Label)"],
        colnames=["Rule Alert (Suspicious)"],
        margins=True,
    )

    return {
        "status": "evaluated",
        "total": total,
        "tp": tp,
        "fp": fp,
        "tn": tn,
        "fn": fn,
        "precision": precision,
        "recall": recall,
        "f1_score": f1,
        "specificity": specificity,
        "false_positive_rate": fpr,
        "accuracy": accuracy,
        "confusion_matrix": crosstab_df.to_dict(),
        "crosstab_dataframe": crosstab_df,
    }


def answer_business_questions(df: pd.DataFrame) -> Dict[str, Dict[str, Any]]:
    """Synthesize concrete data-backed answers to all 10 business questions from Section 34."""
    total_txns = len(df)
    suspicious_count = int(df["Suspicious"].sum())
    suspicious_pct = round((suspicious_count / total_txns) * 100.0, 2)

    # Q2: Which rule generates most alerts?
    pattern_summary = get_pattern_summary(df)
    top_rule_row = pattern_summary.sort_values(by="Alerts", ascending=False).iloc[0]

    # Q3: Trigger 2 or more rules?
    score_ge_2 = int((df["Suspicion_Score"] >= 2).sum())
    score_ge_2_pct = round((score_ge_2 / total_txns) * 100.0, 2)

    # Q4: Transaction types with higher rates
    type_df = get_type_analysis(df)
    top_type = type_df.iloc[0]["Transaction_Type"] if not type_df.empty else "N/A"
    top_type_rate = type_df.iloc[0]["Suspicious_Rate"] if not type_df.empty else 0.0

    # Q5: Channels with higher activity
    ch_df = get_channel_analysis(df)
    top_channel = ch_df.iloc[0]["Channel"] if not ch_df.empty else "N/A"
    top_channel_rate = ch_df.iloc[0]["Suspicious_Rate"] if not ch_df.empty else 0.0

    # Q6: Hours with more suspicious transactions
    hour_df = get_hour_analysis(df)
    top_hour_row = hour_df.sort_values(by="Suspicious", ascending=False).iloc[0] if not hour_df.empty else None
    top_hour = int(top_hour_row["Hour"]) if top_hour_row is not None else 0
    top_hour_count = int(top_hour_row["Suspicious"]) if top_hour_row is not None else 0

    # Q7: Are suspicious transactions larger than normal?
    norm_mean = float(df[df["Suspicious"] == 0]["Amount"].mean()) if (df["Suspicious"] == 0).sum() > 0 else 0.0
    susp_mean = float(df[df["Suspicious"] == 1]["Amount"].mean()) if (df["Suspicious"] == 1).sum() > 0 else 0.0
    amount_diff_ratio = round(susp_mean / norm_mean, 2) if norm_mean > 0 else 0.0

    # Q8: Accounts with repeated suspicious activity
    acc_df = get_account_risk_analysis(df)
    multi_susp_accs = acc_df[acc_df["Suspicious_Transactions"] > 1]
    repeat_acc_count = len(multi_susp_accs)
    top_repeat_acc = acc_df.iloc[0]["Account_ID"] if not acc_df.empty else "N/A"
    top_repeat_txns = int(acc_df.iloc[0]["Suspicious_Transactions"]) if not acc_df.empty else 0

    # Q9: Which rule combinations occur most frequently?
    comb_df = get_rule_combination_analysis(df)
    comb_non_zero = comb_df[comb_df["Rule_Combination"] != "0_0_0"]
    top_comb = comb_non_zero.iloc[0]["Rule_Combination"] if not comb_non_zero.empty else "None"
    top_comb_desc = comb_non_zero.iloc[0]["Description"] if not comb_non_zero.empty else "None"
    top_comb_count = int(comb_non_zero.iloc[0]["Transactions"]) if not comb_non_zero.empty else 0

    # Multi-rule (Score >= 2) combinations
    comb_multi = comb_df[comb_df["Rule_Combination"].isin(["1_1_0", "1_0_1", "0_1_1", "1_1_1"])]
    top_multi_comb = comb_multi.iloc[0]["Rule_Combination"] if not comb_multi.empty else "None"
    top_multi_desc = comb_multi.iloc[0]["Description"] if not comb_multi.empty else "None"
    top_multi_count = int(comb_multi.iloc[0]["Transactions"]) if not comb_multi.empty else 0

    # Q10: Evaluation against historical fraud labels
    eval_res = evaluate_against_ground_truth(df)

    answers = {
        "Q1": {
            "question": "What percentage of transactions are flagged as suspicious?",
            "answer": f"{suspicious_pct}% ({suspicious_count:,} out of {total_txns:,} transactions).",
            "metric": suspicious_pct,
        },
        "Q2": {
            "question": "Which rule generates the most alerts?",
            "answer": f"{top_rule_row['Pattern']} ({top_rule_row['Rule_Name']}) with {top_rule_row['Alerts']:,} alerts ({top_rule_row['Alert_Pct']}% of all transactions).",
            "metric": top_rule_row['Pattern'],
        },
        "Q3": {
            "question": "How many transactions trigger two or more rules?",
            "answer": f"{score_ge_2:,} transactions ({score_ge_2_pct}% of total), which represents all flagged high-priority alerts.",
            "metric": score_ge_2,
        },
        "Q4": {
            "question": "Which transaction types have higher suspicious rates?",
            "answer": f"'{top_type}' exhibits the highest suspicious rate at {top_type_rate}% of its transaction volume.",
            "metric": top_type,
        },
        "Q5": {
            "question": "Which channels show higher suspicious activity?",
            "answer": f"'{top_channel}' shows the highest suspicious rate at {top_channel_rate}% of channel traffic.",
            "metric": top_channel,
        },
        "Q6": {
            "question": "Which hours contain more suspicious transactions?",
            "answer": f"Hour {top_hour:02d}:00 contains the peak number of suspicious transactions ({top_hour_count:,} flagged records), consistent with the late-night risk window.",
            "metric": top_hour,
        },
        "Q7": {
            "question": "Are suspicious transactions generally larger than normal transactions?",
            "answer": f"Yes. Suspicious transactions average ${susp_mean:,.2f} versus ${norm_mean:,.2f} for normal transactions (a {amount_diff_ratio}x increase).",
            "metric": amount_diff_ratio,
        },
        "Q8": {
            "question": "Which accounts have repeated suspicious activity?",
            "answer": f"{repeat_acc_count} accounts have multiple suspicious transactions. The top flagged account is {top_repeat_acc} with {top_repeat_txns} suspicious transactions.",
            "metric": repeat_acc_count,
        },
        "Q9": {
            "question": "Which rule combinations occur most frequently?",
            "answer": f"Overall single anomaly: '{top_comb}' ({top_comb_desc}) with {top_comb_count:,} transactions. Among escalated multi-rule alerts (Score >= 2), '{top_multi_comb}' ({top_multi_desc}) is most frequent with {top_multi_count:,} transactions.",
            "metric": top_multi_comb,
        },
        "Q10": {
            "question": "If verified fraud labels are available, how well do the simple rules identify known fraud cases?",
            "answer": f"The screening rules achieve a Recall of {eval_res.get('recall', 0.0)*100:.1f}%, Precision of {eval_res.get('precision', 0.0)*100:.1f}%, and F1-Score of {eval_res.get('f1_score', 0.0):.3f}, capturing known fraud while maintaining a low False Positive Rate of {eval_res.get('false_positive_rate', 0.0)*100:.2f}%.",
            "metric": eval_res.get('f1_score', 0.0),
        },
    }
    return answers
